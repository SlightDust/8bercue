package dev.sid.fiveberinspector;
import android.os.*;
/** Executes the actual production provider with controlled Binder/clock adapters. */
public final class BootstrapProviderOfflineTest {
 static int checks;
 static void check(boolean ok,String name){checks++;if(!ok)throw new AssertionError(name);}
 static final CompanionBinderProvider provider=new CompanionBinderProvider();
 static Bundle call(String method,Bundle args){return provider.call(method,null,args);}
 static void rejected(String method,Bundle args,String name){boolean blocked=false;try{call(method,args);}catch(SecurityException expected){blocked=true;}check(blocked,name);}
 public static void main(String[]args){
  Binder.uid=2000;SystemClock.now=0;
  check(!call(CompanionBinderProvider.STATE_METHOD,new Bundle()).getBoolean("connected"),"Process absence cannot claim connection");
  rejected(CompanionBinderProvider.CHALLENGE_METHOD,new Bundle(),"No challenge before explicit app action");
  CompanionBinderProvider.beginManagementBootstrap();
  Bundle challenge=call(CompanionBinderProvider.CHALLENGE_METHOD,new Bundle());
  check(OperationTokens.isValid(challenge.getString("nonce")),"Challenge generated by app");
  for(int uid:new int[]{0,1000,10001}){
   Binder.uid=uid;
   for(String method:new String[]{CompanionBinderProvider.STATE_METHOD,CompanionBinderProvider.FEEDBACK_METHOD,CompanionBinderProvider.CHALLENGE_METHOD,CompanionBinderProvider.MANAGEMENT_METHOD})
    rejected(method,challenge,"Reject non-Shell caller "+uid+" "+method);
  }
  Binder.uid=2000;Bundle report=new Bundle(challenge);report.putString("code","STARTING");
  call(CompanionBinderProvider.FEEDBACK_METHOD,report);
  check(CompanionBinderProvider.bootstrapFeedback().equals("STARTING"),"Authenticated progress displayed");
  for(String key:new String[]{"nonce","protocol","versionCode"}){
   Bundle bad=new Bundle(report);if(key.equals("nonce"))bad.putString(key,OperationTokens.create());else bad.putInt(key,-1);
   rejected(CompanionBinderProvider.FEEDBACK_METHOD,bad,"Feedback cannot bypass "+key);
  }
  for(String code:new String[]{"CONNECTED","private ICCID or exception",null}){
   Bundle bad=new Bundle(report);bad.putString("code",code);rejected(CompanionBinderProvider.FEEDBACK_METHOD,bad,"Reject untrusted status "+code);
  }
  check(!call(CompanionBinderProvider.STATE_METHOD,new Bundle()).getBoolean("connected"),"Progress never establishes management");
  SystemClock.now=120000;
  rejected(CompanionBinderProvider.FEEDBACK_METHOD,report,"Expired feedback rejected");
  rejected(CompanionBinderProvider.CHALLENGE_METHOD,new Bundle(),"Expired challenge rejected at exact deadline");
  CompanionBinderProvider.beginManagementBootstrap();
  rejected(CompanionBinderProvider.FEEDBACK_METHOD,report,"Previous window cannot report into retry");
  check(CompanionBinderProvider.bootstrapFeedback().isEmpty(),"Retry clears old errors");
  Bundle next=call(CompanionBinderProvider.CHALLENGE_METHOD,new Bundle());
  Bundle payload=new Bundle(next);payload.putString("apkSha256","wrong");payload.putBinder("managementBinder",new Binder());
  rejected(CompanionBinderProvider.MANAGEMENT_METHOD,payload,"Artifact verification remains mandatory");
  payload.putString("apkSha256","expected-apk-sha");
  payload.putBinder("managementBinder",new Binder(){public String getInterfaceDescriptor(){return "wrong";}});
  rejected(CompanionBinderProvider.MANAGEMENT_METHOD,payload,"Typed interface remains mandatory");
  Binder service=new Binder();payload.putBinder("managementBinder",service);
  check(call(CompanionBinderProvider.MANAGEMENT_METHOD,payload).getBoolean("accepted"),"Only full verified handoff connects");
  check(call(CompanionBinderProvider.STATE_METHOD,new Bundle()).getBoolean("connected"),"State confirms live accepted Binder");
  rejected(CompanionBinderProvider.FEEDBACK_METHOD,next,"Consumed challenge cannot change state");
  rejected(CompanionBinderProvider.MANAGEMENT_METHOD,payload,"One-use challenge cannot replay");
  service.alive=false;
  check(!call(CompanionBinderProvider.STATE_METHOD,new Bundle()).getBoolean("connected"),"Dead Binder cannot report success");
  System.out.println("PASS "+checks+" bootstrap provider authentication/state assertions (actual production provider; simulated Binder)");
 }
}
